const www = process.argv[2];
globalThis.localStorage = { _d:{}, getItem(k){return this._d[k]??null}, setItem(k,v){this._d[k]=v} };
const sent = [];
globalThis.document = { hidden: false, addEventListener() {} };
globalThis.window = { Capacitor: { isNativePlatform: () => true, registerPlugin: n => n === 'WidgetBridge' ? { update: async o => { sent.push(o); } } : null } };
const St = await import(www + '/js/store.js'); const H = await import(www + '/js/habits.js'); const W = await import(www + '/js/widget.js');
St.load();
let fails = 0; const ok = (c, m) => { console.log((c ? 'OK  ' : 'FAIL') + ' ' + m); if (!c) fails++; };
const t = St.today();
ok(W.supported() === true, 'на телефоне виджет поддерживается');
St.S.complete[St.shift(t, -1)] = 1;
ok(await W.syncWidget() === true && sent.length === 1, 'данные отправлены плагину');
const s = sent[0];
ok(s.date === t && s.streak === 1 && s.left === 3 && s.total === 3 && s.doneToday === false, 'снимок: серия 1, осталось 3 из 3, день не закрыт ' + JSON.stringify(s));
St.S.habits.forEach(h => H.setDone(h.id, true));
await W.syncWidget();
const s2 = sent[1];
ok(s2.left === 0 && s2.doneToday === true && s2.streak === 2, 'после выполнения всего: осталось 0, день закрыт, серия 2');
ok(Object.keys(s2).sort().join() === 'date,doneToday,left,streak,total', 'набор полей совпадает с тем, что читает Kotlin');
globalThis.window = {};
ok(W.supported() === false && await W.syncWidget() === false, 'в браузере тихо ничего не делает');
globalThis.window = { Capacitor: { isNativePlatform: () => true, registerPlugin: () => ({ update: async () => { throw new Error('нет плагина'); } }) } };
ok(await W.syncWidget() === false, 'ошибка плагина не ломает приложение');
process.exit(fails ? 1 : 0);
